package com.eternalengine.incident;

import java.util.Locale;

/**
 * Immutable generated incident record.
 */
public final class IncidentRecord {

    private final String incidentId;
    private final IncidentType type;
    private final IncidentKind kind;
    private final int year;
    private final String regionId;
    private final int severity;
    private final double probability;
    private final long seed;
    private final String explanation;

    public IncidentRecord(String incidentId, IncidentType type, int year, String regionId,
                          int severity, double probability, long seed, String explanation) {
        this.incidentId = incidentId == null || incidentId.isBlank() ? "incident_unknown" : incidentId;
        this.type = type == null ? IncidentType.LOCAL_RUMOR : type;
        this.kind = this.type.kind();
        this.year = year;
        this.regionId = regionId == null || regionId.isBlank() ? "global" : regionId;
        this.severity = Math.max(1, Math.min(10, severity));
        this.probability = Math.max(0.0d, Math.min(1.0d, probability));
        this.seed = seed;
        this.explanation = explanation == null ? "Generated by deterministic incident rules" : explanation;
    }

    public String toSummaryString() {
        return String.format(Locale.ROOT, "%s %s year=%d region=%s severity=%d probability=%.3f",
            kind, type, year, regionId, severity, probability);
    }

    public String incidentId() { return incidentId; }
    public IncidentType type() { return type; }
    public IncidentKind kind() { return kind; }
    public int year() { return year; }
    public String regionId() { return regionId; }
    public int severity() { return severity; }
    public double probability() { return probability; }
    public long seed() { return seed; }
    public String explanation() { return explanation; }
}
